#!/usr/bin/env node
// Generates tests/types/shim-parity.ts (PLRNUI-150, ADR 0013) from audit/api/snapshots/*.snapshot: one Expect<Equal<>> per exported
// value (typeof) and per exported type, comparing the legacy shim with the target. The list is never maintained by hand.
//   node scripts/gen-shim-type-parity.mjs [--check]
//   (no flag) write tests/types/shim-parity.ts     --check  exit 1 when the file on disk differs from the snapshots
// Then: node scripts/build-shim.mjs --out dist-shim && npx tsc -p tsconfig.shim-types.json --noEmit
// tsconfig.shim-types.json maps both specifiers: the target to src/, the shim to the generated dist-shim/ output.
// Generic types (a snapshot line carries no type parameters) are compared instantiated with `any` for every parameter; the arity is read
// from the declaration with the TypeScript API, so nothing is listed by hand.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { readIdentity } from "./lib/identity.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "tests/types/shim-parity.ts");
const LEGACY = "@legacy-placeholder/shim"; // the name build-shim.mjs gives the shim while config/package-identity.json has no legacy name

/** Number of type parameters of every exported type of a source entry file. */
function arities(entry) {
  const options = { noEmit: true, strict: true, skipLibCheck: true, jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022 };
  const program = ts.createProgram([entry], options);
  const checker = program.getTypeChecker();
  const module = checker.getSymbolAtLocation(program.getSourceFile(entry));
  const found = new Map();
  for (const symbol of checker.getExportsOfModule(module)) {
    const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
    const count = Math.max(0, ...(resolved.declarations ?? []).map((d) => (ts.isInterfaceDeclaration(d) || ts.isTypeAliasDeclaration(d) || ts.isClassDeclaration(d) ? (d.typeParameters?.length ?? 0) : 0)));
    found.set(symbol.getName(), count);
  }
  return found;
}

function pascal(name) {
  return name.replace(/(^|[_-])(\w)/g, (_m, _s, c) => c.toUpperCase());
}

export function render() {
  const target = readIdentity().current;
  const dir = join(root, "audit/api/snapshots");
  const snapshots = readdirSync(dir).filter((f) => f.endsWith(".snapshot")).sort((a, b) => (a === "root.snapshot" ? -1 : b === "root.snapshot" ? 1 : a.localeCompare(b)));
  const lines = [
    "// GENERATED by scripts/gen-shim-type-parity.mjs from audit/api/snapshots/*.snapshot (PLRNUI-150). Do not edit by hand:",
    "// run `node scripts/gen-shim-type-parity.mjs`. Checked by `npx tsc -p tsconfig.shim-types.json --noEmit` after",
    "// `node scripts/build-shim.mjs --out dist-shim`. Excluded from tsconfig.type-tests.json (the shim specifier only resolves there).",
    "type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;",
    "type Expect<T extends true> = T;",
    "type Mutual<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;",
    "",
  ];
  const body = [];
  for (const file of snapshots) {
    const name = file.replace(/\.snapshot$/, "");
    const sub = name === "root" ? "" : `/${name.replace(/__/g, "/")}`;
    const id = name === "root" ? "Root" : pascal(name);
    lines.push(`import type * as Shim${id} from ${JSON.stringify(LEGACY + sub)};`, `import type * as Target${id} from ${JSON.stringify(target + sub)};`);
    const arity = arities(join(root, "src", sub.slice(1), "index.ts"));
    const args = (symbol) => (arity.get(symbol) ? `<${Array(arity.get(symbol)).fill("any").join(", ")}>` : "");
    body.push("", `// ${sub ? `.${sub}` : "."} (${file})`);
    for (const line of readFileSync(join(dir, file), "utf8").split("\n")) {
      const [kind, symbol] = line.split(" ");
      if (!kind) continue;
      const alias = `_${id}_${symbol}`;
      if (kind === "type") body.push(`export type ${alias} = Expect<Equal<Shim${id}.${symbol}${args(symbol)}, Target${id}.${symbol}${args(symbol)}>>;`);
      else body.push(`export type ${alias} = Expect<Equal<typeof Shim${id}.${symbol}, typeof Target${id}.${symbol}>>;`);
    }
  }
  body.push(
    "",
    "// Negative fixture: a mismatch must be rejected. If this line ever compiles, Equal<> has stopped discriminating.",
    "// @ts-expect-error a type is not equal to an unrelated one",
    `export type _Negative = Expect<Equal<ShimRoot.${firstType(dir, snapshots)}, { unrelated: true }>>;`,
    "// Mutual<> is the fallback for generics where Equal<> is flaky; it must discriminate too.",
    "// @ts-expect-error a type is not mutually assignable with an unrelated one",
    `export type _NegativeMutual = Expect<Mutual<ShimRoot.${firstType(dir, snapshots)}, { unrelated: true }>>;`,
  );
  return `${lines.join("\n")}\n${body.join("\n")}\n`;
}

function firstType(dir, snapshots) {
  for (const line of readFileSync(join(dir, snapshots[0]), "utf8").split("\n")) if (line.startsWith("type ")) return line.split(" ")[1];
  throw new Error("the root snapshot has no type export");
}

function main() {
  const text = render();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(out, "utf8"); } catch { /* missing */ }
    if (current !== text) {
      console.error("gen-shim-type-parity: tests/types/shim-parity.ts is out of date; run node scripts/gen-shim-type-parity.mjs");
      return 1;
    }
    console.log("gen-shim-type-parity: up to date");
    return 0;
  }
  writeFileSync(out, text);
  console.log(`gen-shim-type-parity: wrote ${out.replace(`${root}/`, "")}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
