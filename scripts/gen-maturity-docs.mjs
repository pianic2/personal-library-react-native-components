#!/usr/bin/env node
// Renders docs/maturity.md from the component meta files (PLRNUI-191, ADR 0016). The page lists every component with its
// category and maturity level, so it can never drift from `<Name>.meta.ts`. Reads metadata ONLY through scripts/lib/meta.mjs.
// Usage: node scripts/gen-maturity-docs.mjs [--root <dir>] [--check]
//   (no flag)  writes docs/maturity.md
//   --check    writes nothing; exit 1 when docs/maturity.md is missing or differs from the rendered page
// Exit 0 ok, 1 invalid metadata or stale page, 2 usage or unreadable input. Deterministic: no dates, sorted output.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MetaError, STATUSES, lintMetas, loadMetas } from './lib/meta.mjs';

class UsageError extends Error {}

const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const cell = (text) => String(text).replace(/\s+/g, ' ').trim().replace(/\|/g, '\\|');

// Wording follows docs/policies/stability.md (ladder -> stability label) and ADR 0011.
const LEVELS = {
  prototype: 'Stability label `experimental`: the API can change without notice.',
  demo: 'Label `experimental`, or `beta` once publicly exported and documented. Must pass the demo bar (`npm run maturity:check`).',
  stable: 'Label `stable`: covered by semantic versioning.',
  'production-ready': 'Label `stable`: covered by semantic versioning; the highest level.',
  deprecated: 'Kept for compatibility; removal follows the deprecation policy.',
};

/** Renders the page for loaded and linted entries. `docsExist(path)` says whether a docs page exists (links only to real pages). */
export function render(entries, docsExist) {
  const rows = entries
    .map((entry) => ({ ...entry.meta }))
    .sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));
  const counts = Object.fromEntries(STATUSES.map((status) => [status, rows.filter((row) => row.status === status).length]));
  const lines = [
    '<!-- GENERATED by scripts/gen-maturity-docs.mjs (npm run maturity:docs) from src/components/*/*.meta.ts. Do not edit by hand. -->',
    '',
    '# Component maturity',
    '',
    `Every component declares its level in its \`<Name>.meta.ts\`. This page is generated from those files and lists all ${rows.length} components. What each level promises is described in [Stability](policies/stability.md).`,
    '',
    '## Levels',
    '',
    '| Level | Components | Meaning |',
    '| --- | --- | --- |',
    ...STATUSES.map((status) => `| \`${status}\` | ${counts[status]} | ${cell(LEVELS[status])} |`),
    '',
    '## Components',
    '',
    '| Component | Category | Level | Summary |',
    '| --- | --- | --- | --- |',
  ];
  for (const row of rows) {
    const page = `components/${row.category}/${kebab(row.name)}.md`;
    const name = docsExist(page) ? `[${row.name}](${page})` : row.name;
    lines.push(`| ${name} | ${cell(row.category)} | \`${row.status}\` | ${cell(row.summary)} |`);
  }
  lines.push('');
  return lines.join('\n');
}

function parseArgs(argv, defaultRoot) {
  const opts = { check: false, root: defaultRoot };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--root' && typeof argv[i + 1] === 'string') opts.root = resolve(argv[(i += 1)]);
    else throw new UsageError(`unknown or incomplete argument: ${arg}`);
  }
  return opts;
}

function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const opts = parseArgs(process.argv.slice(2), resolve(here, '..'));
  const entries = loadMetas(opts.root);
  const errors = lintMetas(entries, { root: opts.root });
  if (errors.length > 0) {
    console.error(errors.join('\n'));
    console.error(`${errors.length} metadata problem(s): fix them before generating docs/maturity.md`);
    return 1;
  }
  const page = render(entries, (path) => existsSync(join(opts.root, 'docs', path)));
  const target = join(opts.root, 'docs', 'maturity.md');
  if (opts.check) {
    const actual = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
    if (actual !== page) {
      console.error('docs/maturity.md is missing or out of date. Run npm run maturity:docs.');
      return 1;
    }
    console.log(`docs/maturity.md is up to date (${entries.length} components)`);
    return 0;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, page);
  console.log(`wrote docs/maturity.md (${entries.length} components)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (error) {
    if (error instanceof UsageError || error instanceof MetaError) {
      console.error(`gen-maturity-docs: ${error.message}`);
      process.exitCode = 2;
    } else {
      throw error;
    }
  }
}
