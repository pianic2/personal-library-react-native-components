#!/usr/bin/env node
// Generates the API reference docs/api/** from the TSDoc of the public entry files (PLRNUI-148).
// One page per package.json "exports" entry that has a "types" file (docs/api/<subpath>.md, root -> docs/api/root.md) plus
// docs/api/index.md. Symbols come from the TypeScript compiler API (same export expansion as scripts/public-api-snapshot.mjs);
// the entry file is the source twin of the "types" target (./dist/x.d.ts -> src/x.ts), so no build is needed.
// Every export recorded in audit/api/snapshots/<subpath>.snapshot must appear on its page, otherwise the run fails.
// Usage: node scripts/docs-api.mjs [--check] [--root <dir>]
//   (no flag)  writes docs/api/** (and removes stale generated pages)
//   --check    writes nothing; exit 1 when a page is missing, stale or extra (run without --check to regenerate)
// Exit 0 ok, 1 stale output or a snapshot symbol missing from the reference, 2 usage or input errors.
// Deterministic: sorted output, no dates, no absolute paths.
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import ts from 'typescript';

class UsageError extends Error {}

const HEADER = '<!-- GENERATED by scripts/docs-api.mjs (npm run docs:api) from the TSDoc of the public entry files. Read-only: do not edit by hand. -->';

function parseArgs(argv) {
  const opts = { check: false, root: process.cwd() };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--check') opts.check = true;
    else if (argv[i] === '--root') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) throw new UsageError('--root needs a value');
      opts.root = path.resolve(value);
      i += 1;
    } else throw new UsageError(`unknown argument ${argv[i]}`);
  }
  return opts;
}

function readSubpaths(root) {
  const pkgFile = path.join(root, 'package.json');
  if (!fs.existsSync(pkgFile)) throw new UsageError('package.json not found');
  const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
  const out = [];
  for (const [key, value] of Object.entries(pkg.exports ?? {})) {
    const types = value && typeof value === 'object' ? value.types : undefined;
    if (typeof types !== 'string') continue;
    const match = /^\.\/dist\/(.+)\.d\.ts$/.exec(types);
    if (!match) throw new UsageError(`exports["${key}"].types is not a ./dist/*.d.ts path: ${types}`);
    out.push({ key, name: key === '.' ? 'root' : key.slice(2).replace(/\//g, '__'), specifier: key === '.' ? pkg.name : `${pkg.name}/${key.slice(2)}`, source: `src/${match[1]}.ts` });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

function createProgram(root, entries) {
  let options = { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, jsx: ts.JsxEmit.ReactJSX, strict: true, skipLibCheck: true, noEmit: true };
  const configPath = path.join(root, 'tsconfig.json');
  if (fs.existsSync(configPath)) {
    const read = ts.readConfigFile(configPath, ts.sys.readFile);
    if (read.error) throw new UsageError(`cannot read tsconfig.json: ${ts.flattenDiagnosticMessageText(read.error.messageText, '\n')}`);
    options = { ...ts.parseJsonConfigFileContent(read.config, ts.sys, root).options, noEmit: true };
  }
  return ts.createProgram({ rootNames: entries, options });
}

const oneLine = (text) => text.replace(/\s+/g, ' ').trim();
const cell = (text) => oneLine(text).replace(/\|/g, '\\|').replace(/</g, '&lt;');
const code = (text) => `\`${oneLine(text).replace(/`/g, "'")}\``;

// Expanded mapped/deep types can run to hundreds of KB; the page keeps a readable prefix (the snapshot holds the full shape hash).
const shorten = (text, max = 240) => (text.length > max ? `${text.slice(0, max)} ...` : text);

function kindOf(symbol) {
  const f = symbol.flags;
  if (f & ts.SymbolFlags.Class) return 'class';
  if (f & ts.SymbolFlags.Enum) return 'enum';
  if (f & ts.SymbolFlags.Function) return 'function';
  if (f & (ts.SymbolFlags.Variable | ts.SymbolFlags.Property)) return 'const';
  if (f & ts.SymbolFlags.Namespace && !(f & ts.SymbolFlags.Type)) return 'namespace';
  if (f & ts.SymbolFlags.Type) return 'type';
  return 'const';
}

function docOf(symbol, checker) {
  const summary = ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim();
  const tags = symbol.getJsDocTags(checker).map((t) => ({ name: t.name, text: ts.displayPartsToString(t.text).trim() }));
  return { summary, tags };
}

function renderSymbol(checker, symbol, root) {
  const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const declaration = resolved.valueDeclaration ?? resolved.declarations?.[0];
  const format = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope;
  const show = (type) => shorten(oneLine(checker.typeToString(type, declaration, format)).split(root).join('<root>'));
  const kind = kindOf(resolved);
  const name = symbol.getName();
  const { summary, tags } = docOf(resolved, checker);
  const lines = [`### ${name}`, '', `*${kind}*`, ''];
  if (summary) lines.push(summary, '');
  const extra = tags.filter((t) => ['deprecated', 'example', 'remarks', 'see', 'since', 'defaultValue'].includes(t.name));
  for (const tag of extra) lines.push(`**@${tag.name}** ${tag.text}`.trim(), '');

  const type = declaration ? (kind === 'type' ? checker.getDeclaredTypeOfSymbol(resolved) : checker.getTypeOfSymbolAtLocation(resolved, declaration)) : undefined;
  if (type && kind !== 'type') {
    const sigs = checker.getSignaturesOfType(type, ts.SignatureKind.Call);
    if (sigs.length > 0) lines.push('```ts', ...sigs.map((s) => oneLine(checker.signatureToString(s, declaration, format)).split(root).join('<root>')), '```', '');
    else lines.push(`Type: ${code(show(type))}`, '');
  }
  if (type && kind === 'type') {
    const props = type.isUnion() || type.isIntersection() && type.types.some((t) => !(t.flags & ts.TypeFlags.Object)) ? [] : checker.getPropertiesOfType(type);
    if (props.length > 0) {
      lines.push('| Prop | Type | Required | Description |', '| --- | --- | --- | --- |');
      for (const prop of [...props].sort((a, b) => a.getName().localeCompare(b.getName()))) {
        const pd = prop.valueDeclaration ?? prop.declarations?.[0];
        const propType = pd ? show(checker.getTypeOfSymbolAtLocation(prop, pd)) : 'unknown';
        const optional = (prop.flags & ts.SymbolFlags.Optional) !== 0;
        const pdoc = docOf(prop, checker);
        const dflt = pdoc.tags.find((t) => t.name === 'default' || t.name === 'defaultValue');
        const dep = pdoc.tags.find((t) => t.name === 'deprecated');
        const desc = [pdoc.summary, dflt ? `Default: ${dflt.text}` : '', dep ? `Deprecated. ${dep.text}` : ''].filter(Boolean).join(' ');
        lines.push(`| \`${prop.getName()}\` | ${cell(code(propType))} | ${optional ? 'no' : 'yes'} | ${cell(desc)} |`);
      }
      lines.push('');
    } else {
      lines.push('```ts', `type ${name} = ${show(type)}`, '```', '');
    }
  }
  return { name, kind, text: lines.join('\n') };
}

/** Renders every page; returns Map<relative path, content> and the list of snapshot symbols missing from the pages. */
export function renderAll(root) {
  const subpaths = readSubpaths(root);
  const entries = subpaths.map((s) => path.join(root, s.source));
  for (const [i, e] of entries.entries()) if (!fs.existsSync(e)) throw new UsageError(`entry file ${subpaths[i].source} not found for ${subpaths[i].key}`);
  const program = createProgram(root, entries);
  const checker = program.getTypeChecker();
  const pages = new Map();
  const missing = [];
  const index = [HEADER, '', '# API reference', '', 'Generated from the TSDoc of the public entry files; one page per package entry point. Regenerate with `npm run docs:api`; `npm run docs:api:check` fails on stale output.', '', '| Entry point | Import | Exports |', '| --- | --- | --- |'];
  for (const sub of subpaths) {
    const file = program.getSourceFile(path.join(root, sub.source));
    const moduleSymbol = file && checker.getSymbolAtLocation(file);
    if (!moduleSymbol) throw new UsageError(`${sub.source} is not a module`);
    const symbols = checker.getExportsOfModule(moduleSymbol).map((s) => renderSymbol(checker, s, root)).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    const snapFile = path.join(root, 'audit/api/snapshots', `${sub.name}.snapshot`);
    if (fs.existsSync(snapFile)) {
      const have = new Set(symbols.map((s) => s.name));
      for (const line of fs.readFileSync(snapFile, 'utf8').split('\n').filter(Boolean)) {
        const name = line.split(' ')[1];
        if (!have.has(name)) missing.push(`${sub.name}: ${name}`);
      }
    }
    const page = [HEADER, '', `# ${sub.specifier}`, '', `\`import { ... } from "${sub.specifier}"\``, '', `${symbols.length} exports.`, '', '| Symbol | Kind |', '| --- | --- |', ...symbols.map((s) => `| [${s.name}](#${s.name.toLowerCase()}) | ${s.kind} |`), '', ...symbols.map((s) => s.text)];
    pages.set(`docs/api/${sub.name}.md`, page.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
    index.push(`| [${sub.specifier}](${sub.name}.md) | ${code(`import { ... } from "${sub.specifier}"`)} | ${symbols.length} |`);
  }
  pages.set('docs/api/index.md', index.join('\n') + '\n');
  return { pages, missing };
}

function listExisting(root) {
  const dir = path.join(root, 'docs/api');
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')).map((f) => `docs/api/${f}`) : [];
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const { pages, missing } = renderAll(opts.root);
  if (missing.length > 0) {
    console.error(`API reference is missing ${missing.length} snapshot symbol(s):\n${missing.map((m) => `  ${m}`).join('\n')}`);
    process.exit(1);
  }
  const existing = listExisting(opts.root);
  if (opts.check) {
    const problems = [];
    for (const [file, content] of pages) {
      const full = path.join(opts.root, file);
      if (!fs.existsSync(full)) problems.push(`missing ${file}`);
      else if (fs.readFileSync(full, 'utf8') !== content) problems.push(`stale ${file}`);
    }
    for (const file of existing) if (!pages.has(file)) problems.push(`extra ${file}`);
    if (problems.length > 0) {
      console.error(`API reference is out of date (run: npm run docs:api):\n${problems.map((p) => `  ${p}`).join('\n')}`);
      process.exit(1);
    }
    console.log(`API reference up to date (${pages.size} pages).`);
    return;
  }
  fs.mkdirSync(path.join(opts.root, 'docs/api'), { recursive: true });
  for (const [file, content] of pages) fs.writeFileSync(path.join(opts.root, file), content);
  for (const file of existing) if (!pages.has(file)) fs.rmSync(path.join(opts.root, file));
  console.log(`Wrote ${pages.size} API reference pages to docs/api.`);
}

try {
  main();
} catch (error) {
  if (error instanceof UsageError) {
    console.error(error.message);
    process.exit(2);
  }
  throw error;
}
