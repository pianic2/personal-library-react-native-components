#!/usr/bin/env node
// Test-coverage matrix (PLRNUI-241): which component has which kind of test. Writes docs/test-matrix.md; --check fails when
// the committed file is stale. The component list comes from the meta files (scripts/lib/meta.mjs), so a new component
// shows up without editing this script.
//
// Columns (a cell is "yes" or "-"; a component is matched by a JSX use `<Name` or by an import of `Name` from a project
// path, in code only, comments ignored):
//   unit     a test under tests/components/** other than the two generic files (component-smoke, render-matrix)
//   a11y     a test under tests/accessibility/**
//   theme    a test under tests/theme/**, or a fixture in tests/helpers/fixtures.tsx (the render matrix renders every
//            fixture in light and dark)
//   types    a type test under tests/types/**
//   catalog  docs/components.md links the component page (docs/components/<category>/<kebab-name>.md)
//   visual   a test under tests/visual/**
//   perf     a test under tests/perf/**
// Usage: node scripts/test-matrix.mjs [--check] [--root <dir>]   Exit 0 ok, 1 stale (--check), 2 usage/unreadable input.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MetaError, loadMetas } from './lib/meta.mjs';

class UsageError extends Error {}

export const COLUMNS = ['unit', 'a11y', 'theme', 'types', 'catalog', 'visual', 'perf'];
const GENERIC = new Set(['tests/components/component-smoke.test.tsx', 'tests/components/render-matrix.test.tsx']);
const OUTPUT = 'docs/test-matrix.md';

const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');

function files(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap((entry) => {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) return files(path);
      return /\.(test\.tsx?|ts|tsx|mjs)$/.test(entry.name) ? [path] : [];
    });
}

/** Test files under `dir` (repository-relative paths) with their code (comments removed). */
function loadTests(root, dir) {
  return files(join(root, dir)).map((file) => ({
    path: relative(root, file).split('\\').join('/'),
    code: stripComments(readFileSync(file, 'utf8')),
  }));
}

export function mentions(code, name) {
  const n = escape(name);
  if (new RegExp(`<${n}(?=[\\s/>])`).test(code)) return true;
  const importRe = /import\s+(?:type\s+)?[^;]*?from\s+['"]([^'"]+)['"]/g;
  for (const match of code.matchAll(importRe)) {
    if (!/^(\.|\/|src)/.test(match[1])) continue; // a package import such as react-native is not the component
    if (new RegExp(`\\b${n}\\b`).test(match[0].slice(0, match[0].lastIndexOf('from')))) return true;
  }
  return false;
}

function fixtureNames(root) {
  const file = join(root, 'tests/helpers/fixtures.tsx');
  if (!existsSync(file)) return new Set();
  const text = readFileSync(file, 'utf8');
  const start = text.indexOf('export const fixtures');
  const body = start === -1 ? '' : text.slice(start);
  return new Set([...body.matchAll(/^ {2}([A-Z][A-Za-z0-9]*):/gm)].map((m) => m[1]));
}

export function buildRows(root) {
  const entries = loadMetas(root);
  const missing = entries.filter((e) => !e.meta);
  if (missing.length > 0) throw new MetaError(`component without a meta file: ${missing.map((e) => e.dir).join(', ')}`);
  const sets = {
    unit: loadTests(root, 'tests/components').filter((t) => !GENERIC.has(t.path)),
    a11y: loadTests(root, 'tests/accessibility'),
    theme: loadTests(root, 'tests/theme'),
    types: loadTests(root, 'tests/types'),
    visual: loadTests(root, 'tests/visual'),
    perf: loadTests(root, 'tests/perf'),
  };
  const fixtures = fixtureNames(root);
  const catalogFile = join(root, 'docs/components.md');
  const catalog = existsSync(catalogFile) ? readFileSync(catalogFile, 'utf8') : '';
  return entries
    .map(({ dir, meta }) => {
      const cells = {};
      for (const column of ['unit', 'a11y', 'types', 'visual', 'perf']) cells[column] = sets[column].some((t) => mentions(t.code, dir));
      cells.theme = fixtures.has(dir) || sets.theme.some((t) => mentions(t.code, dir));
      cells.catalog = catalog.includes(`components/${meta.category}/${kebab(dir)}.md`);
      return { name: dir, status: meta.status, cells };
    })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

export function render(rows) {
  const lines = [
    '# Test-coverage matrix',
    '',
    'Generated by `node scripts/test-matrix.mjs`; do not edit by hand. `node scripts/test-matrix.mjs --check` fails when this file is stale.',
    '',
    `Components: ${rows.length}. A cell is \`yes\` when a test of that kind (or the catalog page) refers to the component, \`-\` otherwise.`,
    '',
    '| Dimension | Meaning |',
    '| --- | --- |',
    '| unit | a test under `tests/components/**` other than the generic `component-smoke` and `render-matrix` files |',
    '| a11y | a test under `tests/accessibility/**` |',
    '| theme | a test under `tests/theme/**`, or a fixture in `tests/helpers/fixtures.tsx` (the render matrix renders every fixture in light and dark) |',
    '| types | a type test under `tests/types/**` |',
    '| catalog | `docs/components.md` links the component page |',
    '| visual | a test under `tests/visual/**` |',
    '| perf | a test under `tests/perf/**` |',
    '',
    `| Component | Status | ${COLUMNS.join(' | ')} |`,
    `| --- | --- | ${COLUMNS.map(() => '---').join(' | ')} |`,
  ];
  for (const row of rows) lines.push(`| ${row.name} | ${row.status} | ${COLUMNS.map((c) => (row.cells[c] ? 'yes' : '-')).join(' | ')} |`);
  lines.push(`| **Total** | | ${COLUMNS.map((c) => rows.filter((r) => r.cells[c]).length).join(' | ')} |`, '');
  return lines.join('\n');
}

function parseArgs(argv) {
  const options = { check: false, root: resolve(dirname(fileURLToPath(import.meta.url)), '..') };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') options.check = true;
    else if (arg === '--root') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) throw new UsageError('--root needs a directory');
      options.root = resolve(value);
      i += 1;
    } else throw new UsageError(`unknown argument: ${arg}`);
  }
  return options;
}

function main() {
  let options;
  try {
    options = parseArgs(process.argv.slice(2));
    if (!existsSync(join(options.root, 'src/components'))) throw new UsageError(`no src/components under ${options.root}`);
    const text = render(buildRows(options.root));
    const target = join(options.root, OUTPUT);
    if (options.check) {
      const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
      if (current !== text) {
        console.error(`${OUTPUT} is ${current === null ? 'missing' : 'stale'}; run: node scripts/test-matrix.mjs`);
        process.exit(1);
      }
      console.log(`${OUTPUT} is up to date`);
      return;
    }
    writeFileSync(target, text);
    console.log(`wrote ${OUTPUT}`);
  } catch (error) {
    if (error instanceof UsageError || error instanceof MetaError) {
      console.error(error.message);
      process.exit(2);
    }
    throw error;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
