import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const cli = join(root, "scripts", "gen-maturity-docs.mjs");

type Meta = { status: string; category?: string; summary?: string };

/** A fixture repo with one meta file per component (and a docs page for those listed in `pages`). */
function fixture(components: Record<string, Meta>, pages: string[] = []) {
  const dir = mkdtempSync(join(tmpdir(), "plrnui-191-"));
  const write = (rel: string, text: string) => {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  };
  for (const [name, meta] of Object.entries(components)) {
    const full = {
      name, category: meta.category ?? "layout", status: meta.status, summary: meta.summary ?? "A fixture component.", whenToUse: ["Testing"], whenNotToUse: [],
      composition: { parents: [], children: [], pairsWith: [] }, a11y: [], variants: {}, states: ["default"], platformNotes: [],
      examples: [{ title: name, code: `<${name} />` }],
    };
    write(`src/components/${name}/${name}.meta.ts`, `export const meta = ${JSON.stringify(full)};\n`);
  }
  for (const page of pages) write(`docs/${page}`, "# page\n");
  return { dir, write, done: () => rmSync(dir, { recursive: true, force: true }) };
}

const run = (args: string[]) => spawnSync(process.execPath, [cli, ...args], { cwd: root, encoding: "utf8" });

describe("PLRNUI-191 gen-maturity-docs", () => {
  it("renders every component with its level, sorted by category then name, and links only existing pages", () => {
    const f = fixture(
      { Zeta: { status: "demo", category: "form" }, Alpha: { status: "prototype", category: "layout" }, Beta: { status: "stable", category: "form", summary: "Has | a pipe" } },
      ["components/form/beta.md"]
    );
    try {
      const result = run(["--root", f.dir]);
      assert.equal(result.status, 0, result.stderr);
      const page = readFileSync(join(f.dir, "docs", "maturity.md"), "utf8");
      assert.match(page, /^<!-- GENERATED by scripts\/gen-maturity-docs\.mjs/);
      const rows = page.split("\n").filter((line) => /^\| (\[?)(Alpha|Beta|Zeta)/.test(line));
      assert.deepEqual(
        rows.map((line) => line.split("|")[1]!.trim()),
        ["[Beta](components/form/beta.md)", "Zeta", "Alpha"]
      );
      assert.match(page, /\| `stable` \| 1 \|/);
      assert.match(page, /\| `deprecated` \| 0 \|/);
      assert.match(page, /Has \\\| a pipe/, "pipes in summaries are escaped");
      assert.match(page, /lists all 3 components/);
    } finally {
      f.done();
    }
  });

  it("is deterministic and --check passes on a fresh page and fails on a stale, edited or missing one", () => {
    const f = fixture({ One: { status: "demo" } });
    try {
      assert.equal(run(["--root", f.dir]).status, 0);
      const first = readFileSync(join(f.dir, "docs", "maturity.md"), "utf8");
      assert.equal(run(["--root", f.dir]).status, 0);
      assert.equal(readFileSync(join(f.dir, "docs", "maturity.md"), "utf8"), first);
      assert.equal(run(["--root", f.dir, "--check"]).status, 0);
      writeFileSync(join(f.dir, "docs", "maturity.md"), `${first}\nhand edit\n`);
      const stale = run(["--root", f.dir, "--check"]);
      assert.equal(stale.status, 1);
      assert.match(stale.stderr, /out of date/);
      assert.equal(readFileSync(join(f.dir, "docs", "maturity.md"), "utf8"), `${first}\nhand edit\n`, "--check never writes");
      rmSync(join(f.dir, "docs", "maturity.md"));
      assert.equal(run(["--root", f.dir, "--check"]).status, 1);
      assert.equal(existsSync(join(f.dir, "docs", "maturity.md")), false);
    } finally {
      f.done();
    }
  });

  it("notices a status change in a meta file", () => {
    const f = fixture({ One: { status: "demo" } });
    try {
      run(["--root", f.dir]);
      f.write("src/components/One/One.meta.ts", readFileSync(join(f.dir, "src/components/One/One.meta.ts"), "utf8").replace('"status":"demo"', '"status":"stable"'));
      assert.equal(run(["--root", f.dir, "--check"]).status, 1);
    } finally {
      f.done();
    }
  });

  it("fails closed on invalid metadata: exit 1 and nothing is written", () => {
    const f = fixture({ One: { status: "invented" } });
    try {
      const result = run(["--root", f.dir]);
      assert.equal(result.status, 1);
      assert.match(result.stderr, /status must be one of/);
      assert.equal(existsSync(join(f.dir, "docs", "maturity.md")), false);
    } finally {
      f.done();
    }
  });

  it("fails closed on a component directory without a meta file", () => {
    const f = fixture({ One: { status: "demo" } });
    try {
      f.write("src/components/Orphan/index.ts", "export {};\n");
      const result = run(["--root", f.dir]);
      assert.equal(result.status, 1);
      assert.match(result.stderr, /missing meta file/);
    } finally {
      f.done();
    }
  });

  it("exits 2 for unknown arguments and for a root without components", () => {
    assert.equal(run(["--bogus"]).status, 2);
    assert.equal(run(["--root"]).status, 2);
    const dir = mkdtempSync(join(tmpdir(), "plrnui-191-empty-"));
    try {
      const result = run(["--root", dir]);
      assert.equal(result.status, 2);
      assert.match(result.stderr, /missing directory/);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("the committed docs/maturity.md matches the repository metadata and is listed in the nav", () => {
    const result = run(["--check"]);
    assert.equal(result.status, 0, result.stderr);
    assert.match(readFileSync(join(root, "mkdocs.yml"), "utf8"), /^\s*- Component Maturity: maturity\.md$/m);
  });
});
