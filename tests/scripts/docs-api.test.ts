import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const cli = join(root, "scripts", "docs-api.mjs");

function fixture(source: string, snapshot = "function Greet aaaaaaaaaaaa\ntype GreetProps bbbbbbbbbbbb\n") {
  const dir = mkdtempSync(join(tmpdir(), "plrnui-148-"));
  const write = (rel: string, text: string) => {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  };
  write("package.json", JSON.stringify({ name: "fx", exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.js" } } }));
  write("tsconfig.json", JSON.stringify({ compilerOptions: { strict: true, target: "ES2022", module: "ESNext", moduleResolution: "Bundler", skipLibCheck: true, noEmit: true } }));
  write("src/index.ts", source);
  write("audit/api/snapshots/root.snapshot", snapshot);
  return { dir, write, done: () => rmSync(dir, { recursive: true, force: true }) };
}

const run = (dir: string, args: string[] = []) => spawnSync(process.execPath, [cli, "--root", dir, ...args], { encoding: "utf8" });

const SRC = `/** Props of Greet. */
export type GreetProps = {
  /** Who to greet. */
  name: string;
};
/** Says hello. */
export function Greet(props: GreetProps): string {
  return props.name;
}
`;

describe("PLRNUI-148 docs-api", () => {
  it("generates a read-only page with TSDoc, props and every snapshot symbol", () => {
    const f = fixture(SRC);
    try {
      assert.equal(run(f.dir).status, 0);
      const page = readFileSync(join(f.dir, "docs/api/root.md"), "utf8");
      assert.match(page, /^<!-- GENERATED by scripts\/docs-api\.mjs/);
      assert.match(page, /Says hello\./);
      assert.match(page, /\| `name` \| `string` \| yes \| Who to greet\. \|/);
      assert.equal(run(f.dir, ["--check"]).status, 0);
    } finally {
      f.done();
    }
  });

  it("--check fails when a prop is added without regeneration, and passes after regenerating", () => {
    const f = fixture(SRC);
    try {
      run(f.dir);
      f.write("src/index.ts", SRC.replace("name: string;", "name: string;\n  /** Added later. */\n  loud?: boolean;"));
      const stale = run(f.dir, ["--check"]);
      assert.equal(stale.status, 1);
      assert.match(stale.stderr, /stale docs\/api\/root\.md/);
      run(f.dir);
      assert.equal(run(f.dir, ["--check"]).status, 0);
    } finally {
      f.done();
    }
  });

  it("fails when a snapshot symbol is absent from the reference", () => {
    const f = fixture(SRC, "function Greet aaaaaaaaaaaa\nfunction Gone cccccccccccc\n");
    try {
      const result = run(f.dir);
      assert.equal(result.status, 1);
      assert.match(result.stderr, /root: Gone/);
    } finally {
      f.done();
    }
  });
});
